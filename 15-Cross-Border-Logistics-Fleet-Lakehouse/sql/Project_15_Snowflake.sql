CREATE OR REPLACE TABLE SILVER_CUSTOMS_CLEARANCE
(
SHIPMENT_ID VARCHAR(20),
PAYLOAD_ID VARCHAR(20),
VEHICLE_ID VARCHAR(20),
DESTINATION_COUNTRY VARCHAR(20),
DECLARED_VALUE  NUMBER(10,2),
DUTY_PCT NUMBER(10,1),
DUTY_AMOUNT_DUE NUMBER(10,2),
BORDER_CODE VARCHAR(20),
CLEARANCE_STATUS VARCHAR(20)
);


INSERT INTO SILVER_CUSTOMS_CLEARANCE(SHIPMENT_ID,
                                     PAYLOAD_ID,
                                     VEHICLE_ID,
                                     DESTINATION_COUNTRY,
                                     DECLARED_VALUE,
                                     DUTY_PCT,
                                     DUTY_AMOUNT_DUE,
                                     BORDER_CODE,
                                     CLEARANCE_STATUS)
WITH SILVER_CTE AS
(
SELECT  RAW_PAYLOAD:data.shipment_id::VARCHAR(20) AS SHIPMENT_ID,
        RAW_PAYLOAD:payload_id::VARCHAR(20) AS PAYLOAD_ID,
        RAW_PAYLOAD:data.vehicle_id::VARCHAR(20) AS VEHICLE_ID,
        RAW_PAYLOAD:data.destination_country::VARCHAR(20) AS DESTINATION_COUNTRY,
        RAW_PAYLOAD:data.declared_value::NUMBER(10,2) AS DECLARED_VALUE,
        RAW_PAYLOAD:data.duty_pct::NUMBER(10,1) AS DUTY_PCT,
        RAW_PAYLOAD:data.border_clearance_code::VARCHAR(20) AS BORDER_CODE,
        RAW_PAYLOAD:data.clearance_status::VARCHAR(20) AS CLEARANCE_STATUS
FROM BRONZE_IOT_STREAMS
WHERE RAW_PAYLOAD:payload_type::VARCHAR(20) = 'CUSTOMS'
)
SELECT  SHIPMENT_ID,
        PAYLOAD_ID,
        VEHICLE_ID,
        DESTINATION_COUNTRY,
        DECLARED_VALUE,
        DUTY_PCT,
        ROUND(((DECLARED_VALUE*DUTY_PCT)/100),2) AS DUTY_AMOUNT_DUE,
        BORDER_CODE,
        CLEARANCE_STATUS
FROM SILVER_CTE;


SELECT  SHIPMENT_ID,
        VEHICLE_ID,
        DESTINATION_COUNTRY AS DEST_COUNTRY,
        DECLARED_VALUE,
        DUTY_PCT,
        DUTY_AMOUNT_DUE,
        BORDER_CODE,
        CLEARANCE_STATUS
FROM SILVER_CUSTOMS_CLEARANCE;


CREATE TABLE GOLD_COUNTRY_DUTY_SUMMARY
(
DEST_COUNTRY VARCHAR(20),
TOTAL_CLEARED_VAL NUMBER(12,2),
TOTAL_DUTIES_COLLECTED NUMBER(10,2),
AVG_DUTY_RATE_PCT NUMBER(10,2),
CLEARED_SHIPMENTS NUMBER
);

INSERT INTO GOLD_COUNTRY_DUTY_SUMMARY(DEST_COUNTRY,TOTAL_CLEARED_VAL,TOTAL_DUTIES_COLLECTED,AVG_DUTY_RATE_PCT,CLEARED_SHIPMENTS)
SELECT  DESTINATION_COUNTRY AS DEST_COUNTRY,
        SUM(DECLARED_VALUE) AS TOTAL_CLEARED_VAL,
        SUM(DUTY_AMOUNT_DUE) AS TOTAL_DUTIES_COLLECTED,
        ROUND(AVG(DUTY_PCT),2) AS AVG_DUTY_RATE_PCT,
        COUNT(CLEARANCE_STATUS) AS CLEARED_SHIPMENTS
FROM SILVER_CUSTOMS_CLEARANCE
WHERE CLEARANCE_STATUS = 'CLEARED'
GROUP BY DESTINATION_COUNTRY;


SELECT  DEST_COUNTRY,
        TOTAL_CLEARED_VAL,
        TOTAL_DUTIES_COLLECTED,
        AVG_DUTY_RATE_PCT,
        CLEARED_SHIPMENTS
FROM GOLD_COUNTRY_DUTY_SUMMARY;

