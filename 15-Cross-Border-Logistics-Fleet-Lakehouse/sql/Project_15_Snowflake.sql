UPDATE SILVER_CUSTOMS_CLEARANCE SLV
SET SLV.CLEARANCE_STATUS=OLD_SLV.CLEARANCE_STATUS
FROM (
SELECT CLEARANCE_STATUS
FROM SILVER_CUSTOMS_CLEARANCE
BEFORE (STATEMENT => '01c698d5-3203-330d-0017-d5ea0017db92')
WHERE DESTINATION_COUNTRY = 'CAN'
) OLD_SLV
WHERE SLV.DESTINATION_COUNTRY='CAN';

SELECT  DESTINATION_COUNTRY,
        COUNT_IF(CLEARANCE_STATUS='CLEARED') AS CLEARED_COUNT,
        COUNT_IF(CLEARANCE_STATUS='REJECTED') AS REJECTED_COUNT
FROM SILVER_CUSTOMS_CLEARANCE
GROUP BY DESTINATION_COUNTRY
ORDER BY DESTINATION_COUNTRY;

WITH BRONZE_TOTAL AS
(
SELECT SUM(RAW_PAYLOAD:data.declared_value::NUMBER(10,2)) AS BRONZE_GROSS_TOTAL
FROM BRONZE_IOT_STREAMS
), SILVER_TOTAL AS
(
SELECT SUM(DECLARED_VALUE) AS SILVER_GROSS_TOTAL
FROM SILVER_CUSTOMS_CLEARANCE
), GOLD_TOTAL AS
(
SELECT SUM(TOTAL_CLEARED_VAL) AS GOLD_GROSS_TOTAL
FROM GOLD_COUNTRY_DUTY_SUMMARY
)
SELECT  BRONZE_GROSS_TOTAL,
        SILVER_GROSS_TOTAL,
        GOLD_GROSS_TOTAL,
        CASE 
            WHEN BRONZE_GROSS_TOTAL=SILVER_GROSS_TOTAL
            THEN TRUE
            ELSE FALSE
        END AS RECONCILED_FLAG
FROM BRONZE_TOTAL,SILVER_TOTAL,GOLD_TOTAL;
        
