CREATE TABLE QUARANTINE_CLAIMS_PAYLOAD
(
QUARANTINE_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
RAW_RECORD_TEXT VARCHAR(100),
REASON VARCHAR(100)
);

CREATE FILE FORMAT RAW_TEXT_FORMAT
TYPE = 'CSV'
FIELD_DELIMITER = NONE
RECORD_DELIMITER = '\n';


INSERT INTO QUARANTINE_CLAIMS_PAYLOAD(RAW_RECORD_TEXT,REASON)
SELECT  $1,
        'MALFORMED_JSON_BODY' AS REASON
FROM @RAW_JSON_STAGE/batch3_payloads.json
(
FILE_FORMAT => RAW_TEXT_FORMAT
)
WHERE TRY_PARSE_JSON($1) IS NULL;


SELECT  QUARANTINE_ID,
        RAW_RECORD_TEXT,
        REASON
FROM QUARANTINE_CLAIMS_PAYLOAD;


