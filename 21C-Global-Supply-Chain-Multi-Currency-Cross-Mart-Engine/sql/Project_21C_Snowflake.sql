ON PO.CURRENCY = DIM.CURRENCY
WHERE PO.PO_ID='PO-9001'
),
POST_MERGE AS
(
SELECT  PO.PO_ID,
        ROUND((PO.AMOUNT_LOCAL*DIM.FX_TO_USD),2) AS POST_MERGE_USD
FROM RAW_PO_STG PO
JOIN DIM_CURRENCY_CONFORMED DIM
ON PO.CURRENCY = DIM.CURRENCY
WHERE PO.PO_ID='PO-9001'
)
SELECT PRE.PO_ID,PRE_MERGE_USD, POST_MERGE_USD 
FROM PRE_MERGE PRE,POST_MERGE POST
WHERE PRE.PO_ID = POST.PO_ID;

