SELECT
PO.PO_ID,
PO.SUPPLIER_ID,
CUR.CURRENCY_SK,
CUR.CURRENCY,
PO.AMOUNT_LOCAL,
ROUND(PO.AMOUNT_LOCAL * CUR.FX_TO_USD, 2) AS AMOUNT_USD
FROM raw_po_stg PO
JOIN DIM_CURRENCY_CONFORMED CUR
ON PO.CURRENCY = CUR.CURRENCY;

