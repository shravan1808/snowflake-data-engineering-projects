CREATE VIEW VW_CROSS_MART AS
SELECT  PO_ID,
        SUPPLIER_ID,
        CURRENCY,
        AMOUNT_LOCAL,
        AMOUNT_USD,
        'MATCHED' AS RECOND_STATUS
FROM FACT_GLOBAL_PROCUREMENT;

SELECT * FROM VW_CROSS_MART;

MERGE INTO DIM_CURRENCY_CONFORMED T
USING cdc_fx_updates_stg S
ON T.CURRENCY = S.CURRENCY
WHEN MATCHED THEN
    UPDATE
        SET T.FX_TO_USD = S.FX_TO_USD,
            T.EFFECTIVE_DATE = S.EFFECTIVE_DATE
WHEN NOT MATCHED THEN
    INSERT(CURRENCY_SK, CURRENCY,FX_TO_USD, EFFECTIVE_DATE)
    VALUES(CONCAT('CURR_',S.CURRENCY,'_01'), S.CURRENCY, S.FX_TO_USD, S.EFFECTIVE_DATE);

UPDATE FACT_GLOBAL_PROCUREMENT F
SET AMOUNT_USD = ROUND(F.AMOUNT_LOCAL * D.FX_TO_USD, 2)
FROM DIM_CURRENCY_CONFORMED D
WHERE F.CURRENCY = D.CURRENCY
AND F.PO_ID = 'PO-9001';

SELECT * FROM FACT_GLOBAL_PROCUREMENT;

SELECT
'FX_VARIANCE_TOLERANCE' AS AUDIT_CHECK,
CONCAT(
ROUND(
COALESCE(
SUM(ABS(F.AMOUNT_USD - ROUND(F.AMOUNT_LOCAL * D.FX_TO_USD, 2)))
/ NULLIF(SUM(F.AMOUNT_USD), 0) * 100,
0
),
2
),
'%'
) AS VARIANCE_DETECTED,
CASE
WHEN COALESCE(
SUM(ABS(F.AMOUNT_USD - ROUND(F.AMOUNT_LOCAL * D.FX_TO_USD, 2)))
/ NULLIF(SUM(F.AMOUNT_USD), 0) * 100,
0
) <= 0.01
THEN 'PASSED'
ELSE 'FAILED'
END AS STATUS
FROM FACT_GLOBAL_PROCUREMENT F
JOIN DIM_CURRENCY_CONFORMED D
ON F.CURRENCY = D.CURRENCY;


