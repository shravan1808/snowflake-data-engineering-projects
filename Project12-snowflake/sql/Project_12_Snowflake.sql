CREATE TABLE DIM_STORE
(
STORE_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
STORE_ID NUMBER,
STORE_NAME VARCHAR,
CITY VARCHAR,
STATE VARCHAR,
STORE_MANAGER VARCHAR
);

CREATE TABLE DIM_PRODUCT
(
PRODUCT_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
PRODUCT_ID NUMBER,
PRODUCT_NAME VARCHAR,
CATEGORY VARCHAR,
UNIT_PRICE NUMBER(10,2)
);

CREATE TABLE DIM_CUSTOMER_HYBRID
(
CUSTOMER_KEY NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
CUSTOMER_ID NUMBER,
CUSTOMER_NAME VARCHAR,
CITY VARCHAR,
PREVIOUS_CITY VARCHAR,
STATE VARCHAR,
CURRENT_MEMBERSHIP VARCHAR,
PREVIOUS_MEMBERSHIP VARCHAR,
HISTORICAL_MEMBERSHIP VARCHAR,
SEGMENT VARCHAR,
EFFECTIVE_DATE DATE,
EXPIRY_DATE DATE,
IS_CURRENT BOOLEAN
);

