SELECT  CUSTOMER_ID,
        CUSTOMER_NAME,
        CITY,
        PREVIOUS_CITY,
        STATE,
        CURRENT_MEMBERSHIP,
        PREVIOUS_MEMBERSHIP,
        HISTORICAL_MEMBERSHIP,
        SEGMENT,
        EFFECTIVE_DATE,
        EXPIRY_DATE,
        IS_CURRENT
FROM DIM_CUSTOMER_HYBRID
ORDER BY CUSTOMER_ID,EFFECTIVE_DATE;


SELECT  FS.TRANSACTION_ID,
        FS.TRANSACTION_DATE,
        HYB.CUSTOMER_ID,
        HYB.CUSTOMER_NAME,
        HYB.CITY AS CURRENT_CITY,
        HYB.HISTORICAL_MEMBERSHIP AS MEMBERSHIP_AT_PURCHASE,
        HYB.SEGMENT AS SEGMENT_AT_PURCHASE,
        DS.STORE_NAME,
        DP.PRODUCT_NAME,
        FS.TOTAL_AMOUNT 
FROM FACT_SALES FS
INNER JOIN DIM_CUSTOMER_HYBRID HYB
ON FS.CUSTOMER_KEY=HYB.CUSTOMER_KEY
INNER JOIN DIM_STORE DS
ON FS.STORE_KEY= DS.STORE_KEY
INNER JOIN DIM_PRODUCT DP
ON FS.PRODUCT_KEY=DP.PRODUCT_KEY
WHERE HYB.CUSTOMER_ID=101;
        


SELECT 'STORE DIMENSION RECORDS' AS METRIC, COUNT(*) AS VALUE
FROM DIM_STORE
UNION ALL
SELECT 'PRODUCT DIMENSION RECORDS' AS METRIC, COUNT(*) AS VALUE
FROM DIM_PRODUCT
UNION ALL
SELECT 'TOTAL CUSTOMER DIMENSION RECORDS' AS METRIC, COUNT(*) AS VALUE
FROM DIM_CUSTOMER_HYBRID
UNION ALL
SELECT 'CURRENT CUSTOMER RECORDS' AS METRIC, COUNT(*) AS VALUE
FROM DIM_CUSTOMER_HYBRID
WHERE IS_CURRENT = TRUE
UNION ALL
SELECT 'HISTORICAL CUSTOMER RECORDS' AS METRIC, COUNT(*) AS VALUE
FROM DIM_CUSTOMER_HYBRID
WHERE IS_CURRENT = FALSE
UNION ALL
SELECT 'FACT SALES TRANSACTIONS' AS METRIC, COUNT(*) AS VALUE
FROM FACT_SALES;