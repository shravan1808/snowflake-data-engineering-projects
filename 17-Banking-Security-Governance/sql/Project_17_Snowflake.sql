CREATE OR REPLACE SECURE VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY AS
SELECT  REGION,
        SUM(AMOUNT) AS TOTAL_SETTLED_VAL,
        COUNT(*) AS SETTLED_TXN_COUNT,
        ROUND(AVG(AMOUNT),2) AS AVG_SETTLED_AMOUNT
FROM SILVER_BANK_TRANSACTIONS
WHERE STATUS = 'SETTLED'
GROUP BY REGION;

SELECT * FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
ORDER BY TOTAL_SETTLED_VAL DESC;

