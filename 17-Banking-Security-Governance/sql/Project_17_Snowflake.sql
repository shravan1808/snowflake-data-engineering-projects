WITH BRONZE_TOTAL AS
(
SELECT  SUM(PAYLOAD:amount::NUMBER(10,2)) AS BRONZE_GROSS_TOTAL
FROM BRONZE_BANK_PAYLOADS
), SILVER_TOTAL AS       
(
SELECT SUM(AMOUNT) AS SILVER_GROSS_TOTAL
FROM SILVER_BANK_TRANSACTIONS
), GOLD_TOTAL AS
(
SELECT SUM(TOTAL_SETTLED_VAL) AS GOLD_GROSS_TOTAL
FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
)
SELECT  BRONZE_GROSS_TOTAL,
        SILVER_GROSS_TOTAL,
        GOLD_GROSS_TOTAL,
        CASE 
            WHEN BRONZE_GROSS_TOTAL=SILVER_GROSS_TOTAL AND SILVER_GROSS_TOTAL> GOLD_GROSS_TOTAL
            THEN TRUE
            ELSE FALSE
        END AS RECONCILED_FLAG
FROM BRONZE_TOTAL,SILVER_TOTAL,GOLD_TOTAL;


