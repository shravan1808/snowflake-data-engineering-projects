CREATE TABLE STG_RATINGS
(
RATING_ID VARCHAR(20),
AGENCY VARCHAR(20),
CREDIT_SCORE_BAND VARCHAR(20),
RISK_TIER VARCHAR(20)
);

INSERT INTO STG_RATINGS(RATING_ID,
                        AGENCY,
                        CREDIT_SCORE_BAND,
                        RISK_TIER)
SELECT  VALUE:rating_id::VARCHAR(20) AS RATING_ID,
        VALUE:agency::VARCHAR(20) AS AGENCY,
        VALUE:credit_score_band::VARCHAR(20) AS CREDIT_SCORE_BAND,
        VALUE: risk_tier::VARCHAR(20) AS RISK_TIER
FROM @PRO_20B_STG/raw_ratings.json,
LATERAL FLATTEN(INPUT => $1);

CREATE TABLE STG_BRANCHES
(
BRANCH_ID VARCHAR(20),
BRANCH_NAME VARCHAR(20),
REGION VARCHAR(20)
);

INSERT INTO STG_BRANCHES(BRANCH_ID,
                        BRANCH_NAME,
                        REGION)
SELECT  VALUE:branch_id::VARCHAR(20) AS BRANCH_ID,
        VALUE:branch_name::VARCHAR(20) AS BRANCH_NAME,
        VALUE:region::VARCHAR(20) AS REGION
FROM @PRO_20B_STG/raw_branches.json,
LATERAL FLATTEN(INPUT => $1);

SELECT  'STG_RATINGS' AS STAGING_TABLE,
        COUNT(*) AS RECORD_COUNT
FROM STG_RATINGS
UNION ALL
SELECT  'STG_BRANCHES',
        COUNT(*)
FROM STG_BRANCHES;

