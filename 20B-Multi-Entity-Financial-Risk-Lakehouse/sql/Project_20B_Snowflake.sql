CREATE TABLE FACT_LOAN_APPLICATION_SNAPSHOT
(
APP_ID VARCHAR(20),
CUSTOMER_ID VARCHAR(20),
SUBMITTED_DATE DATE,
UNDERWRITTEN_DATE DATE,
APPROVED_DATE DATE,
DISBURSED_DATE DATE,
LOAN_AMOUNT DECIMAL(10,2)
);

INSERT INTO FACT_LOAN_APPLICATION_SNAPSHOT(APP_ID,
                                           CUSTOMER_ID,
                                           SUBMITTED_DATE,                                                                            UNDERWRITTEN_DATE,
                                           APPROVED_DATE,
                                           DISBURSED_DATE,
                                           LOAN_AMOUNT)
SELECT  VALUE:app_id::VARCHAR(20) AS APP_ID,
        VALUE:customer_id::VARCHAR(20) AS CUSTOMER_ID,
        VALUE:submitted_date::DATE AS SUBMITTED_DATE,
        VALUE:underwritten_date::DATE AS UNDERWRITTEN_DATE,
        VALUE:approved_date::DATE AS APPROVED_DATE,
        VALUE:disbursed_date::DATE AS DISBURSED_DATE,
        VALUE:loan_amount::DECIMAL(10,2) AS LOAN_AMOUNT
FROM @PRO_20B_STG/raw_loan_applications.json,
LATERAL FLATTEN(INPUT => $1);

SELECT * FROM FACT_LOAN_APPLICATION_SNAPSHOT;

CREATE TABLE CDC_LOAN_UPDATES
(
APP_ID VARCHAR(20),
APPROVED_DATE DATE,
DISBURSED_DATE DATE
);

INSERT INTO CDC_LOAN_UPDATES(APP_ID,
                             APPROVED_DATE,
                             DISBURSED_DATE)
SELECT  VALUE:app_id::VARCHAR(20) AS APP_ID,
        VALUE:approved_date::DATE AS APPROVED_DATE,
        VALUE:disbursed_date::DATE AS DISBURSED_DATE
FROM @PRO_20B_STG/cdc_loan_updates.json,
LATERAL FLATTEN(INPUT => $1);

SELECT * FROM CDC_LOAN_UPDATES;

MERGE INTO FACT_LOAN_APPLICATION_SNAPSHOT AS T
USING CDC_LOAN_UPDATES AS S
ON T.APP_ID = S.APP_ID
WHEN MATCHED THEN 
    UPDATE 
        SET T.APPROVED_DATE = S.APPROVED_DATE,
            T.DISBURSED_DATE = S.DISBURSED_DATE
WHEN NOT MATCHED THEN
    INSERT(APP_ID,APPROVED_DATE,DISBURSED_DATE)
    VALUES(S.APP_ID,S.APPROVED_DATE,S.DISBURSED_DATE);

SELECT * FROM FACT_LOAN_APPLICATION_SNAPSHOT
WHERE APP_ID = 'APP-9001';

SELECT  'DATE_SEQUENCE_CHK' AS CHECK_NAME,
        COUNT(*) AS INVALID_SEQUENCES,
        CASE WHEN COUNT(*) = 0 THEN 'PASSED'
        ELSE 'FAILED'
        END AS STATUS
FROM FACT_LOAN_APPLICATION_SNAPSHOT
WHERE SUBMITTED_DATE IS NOT NULL
AND UNDERWRITTEN_DATE IS NOT NULL
AND (
UNDERWRITTEN_DATE < SUBMITTED_DATE
OR (APPROVED_DATE IS NOT NULL
AND APPROVED_DATE < UNDERWRITTEN_DATE)
OR (DISBURSED_DATE IS NOT NULL
AND APPROVED_DATE IS NOT NULL
AND DISBURSED_DATE < APPROVED_DATE)
);

SELECT  APP_ID,
        APPROVED_DATE,
        DISBURSED_DATE
FROM FACT_LOAN_APPLICATION_SNAPSHOT
BEFORE(STATEMENT => '01c6ccf8-0204-8e7c-0005-247e00043456')
WHERE APP_ID='APP-9001';

