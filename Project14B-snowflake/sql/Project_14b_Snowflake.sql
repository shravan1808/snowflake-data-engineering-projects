WITH BRONZE_SUM AS
(
SELECT  SUM(RAW_PAYLOADS:amount::NUMBER(10,2)) AS BRONZE_GROSS_SUM
FROM BRONZE_PAYMENT_PAYLOADS
),SILVER_SUM AS
(
SELECT  SUM(GROSS) AS SILVER_GROSS_SUM
FROM SILVER_CLEANED_TRANSACTIONS
),GOLD_SUM AS
(
SELECT  SUM(TOTAL_APPROVED_GROSS) AS GOLD_GROSS_SUM
FROM GOLD_MERCHANT_SETTLEMENTS
)
SELECT  BRONZE_GROSS_SUM,
        SILVER_GROSS_SUM,
        GOLD_GROSS_SUM,
        CASE 
            WHEN BRONZE_GROSS_SUM=SILVER_GROSS_SUM
            THEN TRUE 
            ELSE FALSE
        END AS DATA_MATCH_FLAG
FROM BRONZE_SUM,SILVER_SUM,GOLD_SUM;
        
